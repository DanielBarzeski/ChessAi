    public static final long[] WHITE_PASSED_PAWN_MASKS = new long[64];
    public static final long[] BLACK_PASSED_PAWN_MASKS = new long[64];
    public static final long[] WHITE_SUPPORT_MASKS = new long[64];
    public static final long[] BLACK_SUPPORT_MASKS = new long[64];

    // בונוסים לרגלי עובר לפי רנק (מ-0 עד 7). רגלי מתקדם מקבל בונוס משמעותי במיוחד ב-EG.
    public static final int[] PASSED_PAWN_BONUS_MG = {0, 0, 5, 10, 20, 40, 80, 0};
    public static final int[] PASSED_PAWN_BONUS_EG = {0, 10, 20, 40, 80, 140, 240, 0};

    static {
        for (int sq = 0; sq < 64; sq++) {
            int file = sq % 8;
            int rank = sq / 8;

            long whitePassed = 0L;
            long blackPassed = 0L;
            long whiteSupport = 0L;
            long blackSupport = 0L;

            // חישוב מסכות לרגלי עובר (טור נוכחי וטורים שכנים קדימה)
            for (int r = 0; r < 8; r++) {
                for (int f = 0; f < 8; f++) {
                    int target = r * 8 + f;
                    if (Math.abs(f - file) <= 1) {
                        if (r > rank) {
                            whitePassed |= (1L << target);
                        }
                        if (r < rank) {
                            blackPassed |= (1L << target);
                        }
                    }
                }
            }
            WHITE_PASSED_PAWN_MASKS[sq] = whitePassed;
            BLACK_PASSED_PAWN_MASKS[sq] = blackPassed;

            // חישוב מסכות תמיכה (האם יש רגלי תומך מאחור באלכסון)
            if (file > 0 && sq >= 9) whiteSupport |= (1L << (sq - 9));
            if (file < 7 && sq >= 7) whiteSupport |= (1L << (sq - 7));
            if (file > 0 && sq <= 56) blackSupport |= (1L << (sq + 7));
            if (file < 7 && sq <= 54) blackSupport |= (1L << (sq + 9));

            WHITE_SUPPORT_MASKS[sq] = whiteSupport;
            BLACK_SUPPORT_MASKS[sq] = blackSupport;
        }
    }

